export function permissionLabel(name: string, description?: string | null): string {
  const source = permissionDescriptions[name];
  if (source && (!description || description === source)) return t(source);
  const synced = actionDescriptions[name];
  if (synced && description === synced) return t(synced);
  return description || name;
}
